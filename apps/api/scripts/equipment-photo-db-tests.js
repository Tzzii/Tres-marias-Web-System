import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { adminAccount, client, closePool, pool, requireWriteConsent, runDir, startApi, tokenFor } from './lib/harness.js';

requireWriteConsent({ writesOk: process.argv.includes('--writes-test-data') }, 'Equipment photo integration check');
const uploadDir = path.join(runDir(), 'equipment-photos');
const PNG = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==', 'base64');
const values = { name: `Equipment Photo Check ${crypto.randomBytes(6).toString('hex')}`, category: 'Furniture', total: 45, lowStockAt: 5, rentable: true, rentPrice: 100, damageFee: 200, notes: '' };
const form = (body, bytes = PNG) => {
  const data = new FormData();
  data.append('item', JSON.stringify(body));
  data.append('photo', new Blob([bytes], { type: 'image/png' }), 'equipment.png');
  return data;
};
const files = () => fs.existsSync(path.join(uploadDir, 'equipment')) ? fs.readdirSync(path.join(uploadDir, 'equipment')) : [];
let api;
let id;
let checks = 0;
const passed = (label) => { checks += 1; console.log(`PASS ${label}`); };
try {
  const admin = tokenFor(await adminAccount(), 'admin');
  api = await startApi({ env: { UPLOAD_DIR: uploadDir }, label: 'equipment-photo-check' });
  const call = client(api.base);
  let result = await call('POST', '/admin/inventory', { token: admin, body: { items: [values] } });
  assert.equal(result.status, 201);
  id = result.body[0].id;
  const code = result.body[0].code;
  assert.equal(result.body[0].photoVersion, null);
  result = await call('PATCH', `/admin/inventory/${id}`, { token: admin, form: form(values) });
  assert.equal(result.status, 200);
  let version = result.body.photoVersion;
  assert.ok(version);
  assert.equal(result.body.total, 45);
  assert.equal(result.body.available, 45);
  assert.equal(result.body.photo_key, undefined);
  assert.equal(files().length, 1);
  passed('inventory save publishes one photo without changing the 45 pieces in stock');
  let publicList = await call('GET', '/rental-items');
  let rental = publicList.body.find((item) => item.id === id);
  assert.equal(rental.photoVersion, version);
  assert.equal(rental.code, code);
  assert.equal(rental.total, undefined);
  const catalog = await call('GET', '/catalog');
  assert.equal(catalog.body.rentals.find((item) => item.id === id).photoVersion, version);
  passed('public rental list and booking catalog share the inventory photo version');
  const publicUrl = (v = version) => `${api.base}/rental-items/${id}/photo?v=${encodeURIComponent(v)}`;
  let response = await fetch(publicUrl());
  assert.equal(response.status, 200);
  assert.equal(response.headers.get('content-type'), 'image/png');
  assert.equal(response.headers.get('cross-origin-resource-policy'), 'cross-origin');
  assert.deepEqual(Buffer.from(await response.arrayBuffer()), PNG);
  passed('customers can read the uploaded photo across portal origins');
  result = await call('PATCH', `/admin/inventory/${id}`, { form: form(values) });
  assert.equal(result.status, 401);
  assert.equal((await call('GET', `/admin/inventory/${id}/photo`)).status, 401);
  const [[customer]] = await pool.query('SELECT id, name, password_changed_at AS passwordChangedAt FROM customers LIMIT 1');
  if (customer) {
    result = await call('PATCH', `/admin/inventory/${id}`, { token: tokenFor(customer, 'customer'), form: form(values) });
    assert.equal(result.status, 403);
  }
  assert.equal(files().length, 1);
  passed('only admin sessions can change equipment photos');
  result = await call('PATCH', `/admin/inventory/${id}`, { token: admin, body: { ...values, notes: 'Keep the photo.' } });
  assert.equal(result.status, 200);
  assert.equal(result.body.photoVersion, version);
  passed('ordinary inventory edits preserve the uploaded picture');
  const oldVersion = version;
  result = await call('PATCH', `/admin/inventory/${id}`, { token: admin, form: form(values, Buffer.concat([PNG, Buffer.from('replacement')])) });
  assert.equal(result.status, 200);
  version = result.body.photoVersion;
  assert.notEqual(version, oldVersion);
  assert.equal(files().length, 1);
  assert.equal((await fetch(publicUrl(oldVersion))).status, 404);
  passed('replacement updates the version and cleans up the previous photo');
  result = await call('PATCH', `/admin/inventory/${id}`, { token: admin, form: form({ ...values, total: 99 }, Buffer.from('<svg>not a photo</svg>')) });
  assert.equal(result.status, 400);
  assert.equal(result.body.meta.field, 'photo');
  result = await call('GET', '/admin/inventory', { token: admin });
  assert.equal(result.body.find((item) => item.id === id).total, 45);
  assert.equal(result.body.find((item) => item.id === id).photoVersion, version);
  passed('invalid image rolls back both stock edits and the photo');
  result = await call('PATCH', `/admin/inventory/${id}`, { token: admin, form: form({ ...values, lowStockAt: 100 }) });
  assert.equal(result.status, 400);
  assert.equal(files().length, 1);
  passed('invalid inventory fields do not save an uploaded file');
  result = await call('PATCH', `/admin/inventory/${id}`, { token: admin, form: form({ ...values, removePhoto: true }) });
  assert.equal(result.status, 400);
  assert.equal(files().length, 1);
  const large = Buffer.alloc(20 * 1024 * 1024 + 1);
  PNG.copy(large);
  result = await call('PATCH', `/admin/inventory/${id}`, { token: admin, form: form(values, large) });
  assert.equal(result.status, 400);
  assert.equal(files().length, 1);
  passed('conflicting removal and oversized uploads leave the saved photo intact');
  result = await call('PATCH', `/admin/inventory/${id}`, { token: admin, body: { ...values, rentable: false } });
  assert.equal(result.status, 200);
  assert.equal((await fetch(publicUrl())).status, 404);
  assert.equal((await call('GET', `/admin/inventory/${id}/photo`, { token: admin })).status, 200);
  await call('PATCH', `/admin/inventory/${id}`, { token: admin, body: values });
  await call('POST', '/admin/inventory/archive', { token: admin, body: { ids: [id], archived: true } });
  assert.equal((await fetch(publicUrl())).status, 404);
  assert.equal((await call('GET', `/admin/inventory/${id}/photo`, { token: admin })).status, 200);
  passed('archived and non-rentable photos remain private to the admin');
  await call('POST', '/admin/inventory/archive', { token: admin, body: { ids: [id], archived: false } });
  result = await call('PATCH', `/admin/inventory/${id}`, { token: admin, body: { ...values, removePhoto: true } });
  assert.equal(result.status, 200);
  assert.equal(result.body.photoVersion, null);
  assert.equal(files().length, 0);
  assert.equal((await fetch(publicUrl())).status, 404);
  publicList = await call('GET', '/rental-items');
  rental = publicList.body.find((item) => item.id === id);
  assert.equal(rental.photoVersion, null);
  assert.equal(rental.code, code);
  passed('use mock photo removes the upload and retains the stable sample identity');
  console.log(`${checks} equipment photo integration checks passed.`);
} finally {
  if (api) await api.stop();
  if (id) {
    await pool.query('DELETE FROM inventory_history WHERE item_id = ?', [id]);
    await pool.query('DELETE FROM inventory_items WHERE id = ? AND name = ?', [id, values.name]);
  }
  for (const file of files()) fs.unlinkSync(path.join(uploadDir, 'equipment', file));
  await closePool();
  console.log('Temporary test item and photos cleaned up. Existing inventory unchanged.');
}
